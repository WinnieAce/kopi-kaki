// Cuts Noto Serif SC Black down to the Chinese characters the app actually shows (the drinks' Chinese
// names and the signboard), so the offline download stays small. Writes src/fonts/zh/. Run before builds.
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { UI_CHINESE } from '../src/content/chineseUi'

/** The distinct Chinese characters in `text`, in code-point order. */
export function cjkCharacters(text: string): string[] {
  return [...new Set(text.match(/\p{Script=Han}/gu) ?? [])].sort((a, b) => a.codePointAt(0)! - b.codePointAt(0)!)
}

/** `U+5496,U+5561-5562` as [start, end] code-point pairs. */
function parseRanges(range: string): [number, number][] {
  return range.split(',').map((part) => {
    const [a, b] = part.trim().replace(/^U\+/i, '').split('-')
    return [parseInt(a, 16), parseInt(b ?? a, 16)]
  })
}

/** Every character named by the `unicode-range` declarations in a stylesheet. */
export function coveredCharacters(css: string): Set<string> {
  const covered = new Set<string>()
  for (const [, range] of css.matchAll(/unicode-range:\s*([^;]+);/g)) {
    for (const [a, b] of parseRanges(range)) for (let cp = a; cp <= b; cp++) covered.add(String.fromCodePoint(cp))
  }
  return covered
}

const rangeOf = (chars: string[]) => chars.map((c) => `U+${c.codePointAt(0)!.toString(16)}`).join(',')

async function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..')
  const drinks: { chinese?: string }[] = JSON.parse(readFileSync(join(root, 'src/content/drinks.json'), 'utf8'))
  const needed = cjkCharacters(drinks.map((d) => d.chinese ?? '').join('') + UI_CHINESE.join(''))

  const source = join(root, 'node_modules/@fontsource/noto-serif-sc')
  const css = readFileSync(join(source, '900.css'), 'utf8')
  const out = join(root, 'src/fonts/zh')
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })

  const { default: subsetFont } = await import('subset-font')
  const faces: string[] = []
  let remaining = needed
  for (const [, block] of css.matchAll(/@font-face\s*{([^}]*)}/g)) {
    const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1]
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1]
    if (!file || !range) continue
    const inRange = new Set(coveredCharacters(`unicode-range: ${range};`))
    const chars = remaining.filter((c) => inRange.has(c))
    if (chars.length === 0) continue
    remaining = remaining.filter((c) => !inRange.has(c))

    const name = `noto-serif-sc-900-${faces.length}.woff2`
    const subset = await subsetFont(readFileSync(join(source, 'files', file)), chars.join(''), { targetFormat: 'woff2' })
    writeFileSync(join(out, name), subset)
    faces.push(
      [
        '@font-face {',
        "  font-family: 'Noto Serif SC';",
        '  font-style: normal;',
        '  font-weight: 900;',
        '  font-display: swap;',
        `  src: url('./${name}') format('woff2');`,
        `  unicode-range: ${rangeOf(chars)};`,
        '}',
      ].join('\n'),
    )
  }
  if (remaining.length > 0) throw new Error(`Noto Serif SC has no glyphs for: ${remaining.join(' ')}`)

  writeFileSync(join(out, 'zh.css'), `/* Generated by scripts/subset-chinese-font.ts. Do not edit. */\n${faces.join('\n\n')}\n`)
  const bytes = readdirSync(out).reduce((sum, f) => sum + statSync(join(out, f)).size, 0)
  console.log(`Chinese font: ${needed.length} characters in ${faces.length} file(s), ${(bytes / 1024).toFixed(1)} KB.`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main()
